# calculator.py

def calculate(a, b):
    result = a + b
    return result


print("Calculator Program Start!")
print(calculate(2, 122))

# 빼기
def minus(a, b):
    result = a - b
    return result
    
print(minus(2, 122))

# 곱하기
def multiple(f, u):
    result = f * u
    return result
    
print(multiple(2, 122))

