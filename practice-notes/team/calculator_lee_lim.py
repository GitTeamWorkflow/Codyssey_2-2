# calculator.py

# 더하기
def calculate(a, b):
    result = a + b
    return result

# 빼기
def minus(a, b):
    result = a - b
    return result

# 곱하기
def multiple(f, u):
    result = f * u
    return result

# 나누기
def divide(d, i):
    result = d / i
    return result

print("Calculator Program Start!")
print(calculate(2, 122))
print(minus(2, 122))
print(multiple(2, 122))
print(divide(2, 122))